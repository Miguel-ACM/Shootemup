if __name__ == "__main__":
    size = 192
    canvas = Image.new("RGBA",(4*size,4*size))
    surface = ImageDraw.Draw(canvas)
    for i, motif in enumerate([fish, teapot, cat, stairs, boat, key, gramophone, shell,
                              lantern, whale, jug, umbrella, violin, butterfly, window, pear]):
        motif(Brush((i%4+.5)*size,(i//4+.5)*size,1.20,surface=surface))
    noise = np.random.default_rng(1412)
    paint = np.asarray(canvas).copy()
    grain = noise.normal(0,2,(size*4,size*4,1))
    paint[:,:,:3] = np.clip(paint[:,:,:3].astype(float)+grain,0,255)
    paint[paint[:,:,3]==0,:3]=0
    Image.fromarray(paint).save(Path(__file__).resolve().parents[1]/"Assets/Resources/DreamStudies.png")
