"""Small painted studies for the Dream canvas. Each study has a transparent paper edge."""
from math import cos, sin, pi
from pathlib import Path
import numpy as np
from PIL import Image, ImageDraw
from paint_dream_procession import Brush, ink, blue, violet, rose, rust, ochre, sand, jade, chalk, eye


def fish(b):
    b.shape(ink,(-67,-5),(-35,-28),(5,-24),(29,-6),(62,-34),(53,26),(25,11),(-6,28),(-42,18))
    b.shape(jade,(-61,-4),(-32,-22),(3,-19),(24,-4),(-15,2),(-38,13))
    b.shape(ochre,(-38,13),(15,-4),(22,9),(-5,23))
    b.shape(rose,(32,0),(57,-25),(51,18))
    eye(b,-39,-4,.52)
    for j in range(4): b.line(blue,2,(-8+j*9,-12),(-17+j*9,0),(-10+j*9,10))


def teapot(b):
    b.curve(ochre,11,(17,-19),(68,-51),(69,32),(24,20))
    b.shape(ink,(-33,-24),(26,-18),(37,8),(29,33),(-17,42),(-37,17),(-63,-12),(-66,-25),(-48,-21),(-27,-1))
    b.shape(rose,(-27,-19),(0,-18),(-8,32),(-19,35),(-31,15),(-60,-17),(-52,-16),(-26,3))
    b.shape(ochre,(3,-18),(23,-14),(32,6),(25,28),(-5,33))
    b.shape(jade,(-31,-25),(-14,-36),(5,-39),(27,-19))
    b.oval(-6,-39,7,6,ink)
    b.curve(chalk,2,(-50,-29),(-34,-46),(-69,-44),(-46,-62))


def cat(b):
    b.curve(ink,10,(2,40),(71,62),(60,-16),(35,-5))
    b.oval(2,21,30,31,blue)
    b.shape(ink,(-44,-52),(-23,-34),(-4,-37),(16,-56),(21,-7),(-7,9),(-36,-5))
    b.shape(ochre,(-39,-43),(-22,-29),(-6,-32),(-11,2),(-31,-8))
    b.shape(rose,(-6,-31),(11,-43),(16,-10),(-8,3))
    eye(b,-24,-18,.38); eye(b,6,-19,.37)
    b.line(chalk,2,(-19,-2),(-42,0),(-57,-3)); b.line(chalk,2,(5,-3),(37,-9))


def stairs(b):
    b.shape(blue,(-57,31),(-7,-49),(55,-27),(6,52))
    for j in range(7):
        x=-50+j*7;y=29-j*10
        b.shape(ochre,(x,y),(x+43,y+15),(x+50,y+9),(x+7,y-6))
        b.line(ink,3,(x,y+4),(x+43,y+19),(x+50,y+12))
    b.line(rose,3,(-39,27),(-39,-5),(8,-66),(9,-37))


def boat(b):
    b.shape(ink,(-59,17),(-9,27),(61,7),(38,37),(-21,47))
    b.shape(rust,(-49,22),(-7,32),(48,15),(35,29),(-20,41))
    b.line(ink,4,(-4,28),(6,-57))
    b.shape(sand,(3,-52),(-37,10),(-3,17))
    b.shape(jade,(10,-41),(40,4),(3,13))
    b.curve(blue,3,(-67,49),(-36,36),(-19,64),(58,38))


def key(b):
    b.line(ink,14,(-35,27),(43,-39)); b.line(ochre,8,(-35,27),(43,-39))
    b.oval(-33,28,23,21,ink); b.oval(-33,28,18,16,ochre); b.oval(-33,28,9,9,blue)
    b.line(ochre,8,(33,-28),(45,-16),(52,-22))
    b.line(ochre,7,(18,-19),(28,-8))


def gramophone(b):
    b.shape(ink,(-42,24),(23,11),(48,27),(-14,46),(-42,40))
    b.shape(rust,(-38,25),(21,15),(39,25),(-14,39))
    b.oval(-7,25,20,6,ink); b.oval(-7,24,6,3,ochre)
    b.curve(ochre,6,(18,21),(49,0),(6,1),(17,-25))
    b.shape(ochre,(16,-9),(-39,-26),(-46,-50),(-32,-56),(25,-34))
    b.shape(ink,(-40,-48),(-32,-51),(13,-33),(14,-23),(-23,-31))
    for j in range(3): b.line(sand,2,(-35+j*9,-37+j*4),(15,-16))


def shell(b):
    b.shape(ink,(-56,6),(-39,-30),(-10,-49),(24,-46),(48,-27),(57,2),(44,28),(7,42),(-24,28))
    for i in range(8):
        a=pi*(1.07+i*.12);d=a+.37
        b.shape([rose,ochre,jade,violet][i%4],(-7,31),(49*cos(a),-2+42*sin(a)),(49*cos(d),-2+42*sin(d)))
    b.curve(ink,3,(-36,1),(-21,-35),(19,-34),(35,-4))


