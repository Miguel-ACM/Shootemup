def butterfly(b):
    for side in (-1,1):
        def wing(col,*pts): b.shape(col,*[(side*x,y) for x,y in pts])
        wing(ink,(0,3),(17,-35),(52,-49),(58,-18),(35,6),(43,28),(28,41),(4,19))
        wing(rose,(5,0),(21,-31),(48,-41),(51,-21),(28,4))
        wing(jade,(6,7),(27,7),(37,26),(26,32),(11,18))
        b.oval(side*36,-21,7,9,ochre)
    b.line(ink,4,(0,-21),(0,22))


def window(b):
    b.shape(ink,(-48,-37),(27,-49),(52,-25),(47,43),(-38,50))
