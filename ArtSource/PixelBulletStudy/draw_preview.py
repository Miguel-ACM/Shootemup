def sprite(main, highlight, art):
    rows = dedent(art).strip("\n").splitlines()
    width = max(map(len, rows))
    # A one-pixel safety margin allows the ink contour around every outer pixel.
    result = Image.new("RGBA", (width + 2, len(rows) + 2))
    palette = {
        "b": tuple(round(v * .57) for v in main) + (255,),
        "m": main + (255,), "h": highlight + (255,),
        "p": (255, 160, 81, 255),
    }
    body = {(x + 1, y + 1): palette[c]
            for y, row in enumerate(rows) for x, c in enumerate(row)
            if c != "."}
    for x, y in body:
        for dx, dy in ((-1, 0), (1, 0), (0, -1), (0, 1)):
            if (x + dx, y + dy) not in body:
                result.putpixel((x + dx, y + dy), INK)
    for point, color in body.items():
        result.putpixel(point, color)
    return result.crop(result.getbbox())


def font(size):
    return ImageFont.truetype("C:/Windows/Fonts/consola.ttf", size)


def centre(draw, text, x, y, size=15, fill=TEXT):
    draw.text((x, y), text, font=font(size), fill=fill, anchor="mt")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "sprites").mkdir(exist_ok=True)
    sheet = Image.new("RGB", (1120, 960), BG)
    draw = ImageDraw.Draw(sheet)
    draw.text((30, 22), "PIXEL STUDY 01", font=font(24), fill=TEXT)
    draw.text((1090, 27), "PREVIEW ONLY / NO GAME CHANGES", font=font(14), fill=MUTED, anchor="rt")
    for index, (name, base, light, pixels) in enumerate(DESIGNS):
        image = sprite(base, light, pixels)
        image.save(OUT / "sprites" / (name.lower().replace(" ", "_") + ".png"))
        x, y = (index % 4) * 280, 76 + (index // 4) * 282
        centre(draw, name, x + 140, y + 5, 17)
        enlarged = image.resize((image.width * 6, image.height * 6), Image.Resampling.NEAREST)
        sheet.paste(enlarged, (x + (280 - enlarged.width) // 2, y + 40 + (126 - enlarged.height) // 2), enlarged)
        centre(draw, f"{image.width} x {image.height} px   /   6x above", x + 140, y + 182, 12, MUTED)
        for offset, bg in ((28, (10, 15, 23)), (146, (202, 216, 218))):
            draw.rectangle((x + offset, y + 209, x + offset + 104, y + 253), fill=bg)
            sheet.paste(image, (x + offset + 25 - image.width // 2, y + 231 - image.height // 2), image)
            double = image.resize((image.width * 2, image.height * 2), Image.Resampling.NEAREST)
            sheet.paste(double, (x + offset + 72 - double.width // 2, y + 231 - double.height // 2), double)
    draw.text((30, 934), "Authored pixel maps | 1x + 2x samples on dark and light | No glow, gradients or image generation", font=font(13), fill=MUTED)
    sheet.save(OUT / "preview.png")
    print(f"Saved {OUT / 'preview.png'} and {len(DESIGNS)} transparent sprites.")


if __name__ == "__main__":
    main()
